def extract(lib_text: str, name: str):
    """从库里抽一条动作正文；返回 (正文, 起始行号) 或 (None, None)。"""
    lines = lib_text.splitlines()
    start = None
    for i, ln in enumerate(lines):
        if ln.strip() == f'## {name}':
            start = i + 1
            break
    if start is None:
        return None, None
    end = len(lines)
    for j in range(start, len(lines)):
        if lines[j].startswith('## '):        # 只认二级标题；### 小节属于本条
            end = j
            break
    body = lines[start:end]
    while body and body[-1].strip() in ('', '---'):
        body.pop()
    return '\n'.join(body).strip(), start + 1


def rewrite(text: str, patches):
    for old, new in SUBST:
        text = text.replace(old, new)
    for old, new in (patches or []):
        if old not in text:
            print(f'  ⚠ 补丁未命中：{old[:24]}…')
        text = text.replace(old, new)
    return text


